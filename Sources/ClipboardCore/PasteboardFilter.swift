import AppKit
import Foundation

public enum PasteboardAccessState: Equatable, Sendable {
    case unsupportedOS
    case defaultPrompt
    case askOnAccess
    case alwaysAllow
    case alwaysDeny

    public var statusText: String {
        switch self {
        case .unsupportedOS:
            return "当前 macOS 版本无需额外剪贴板授权"
        case .defaultPrompt:
            return "首次读取外部剪贴板时系统将询问授权"
        case .askOnAccess:
            return "每次读取前询问（建议在系统设置中改为「始终允许」）"
        case .alwaysAllow:
            return "已允许自动读取剪贴板"
        case .alwaysDeny:
            return "已被系统拒绝读取剪贴板，请在「系统设置 → 隐私与安全性」中允许"
        }
    }

    public var needsUserAttention: Bool {
        switch self {
        case .alwaysDeny, .askOnAccess:
            return true
        case .unsupportedOS, .defaultPrompt, .alwaysAllow:
            return false
        }
    }
}

public enum PasteboardFilter {
    /// Clipboard 自身写回剪贴板时附带的标记类型，监听层据此跳过自写回。
    public static let internalCopyType = NSPasteboard.PasteboardType("dev.clipboard.internal-copy")

    /// macOS 与常见密码管理器/文本扩展工具使用的敏感、临时或自动生成标记。
    /// 注意：并非所有密码工具都会写入这些标记，不应假设能识别所有密码。
    public static let ignoredTypeRawValues: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        internalCopyType.rawValue,
    ]

    public static func shouldIgnore(types: [NSPasteboard.PasteboardType]) -> Bool {
        types.contains { ignoredTypeRawValues.contains($0.rawValue) }
    }

    public static func shouldIgnore(pasteboard: NSPasteboard) -> Bool {
        if let boardTypes = pasteboard.types, shouldIgnore(types: boardTypes) {
            return true
        }
        if let items = pasteboard.pasteboardItems {
            for item in items where shouldIgnore(types: item.types) {
                return true
            }
        }
        return false
    }

    public static func accessState(for pasteboard: NSPasteboard) -> PasteboardAccessState {
        if #available(macOS 15.4, *) {
            switch pasteboard.accessBehavior {
            case .default:
                return .defaultPrompt
            case .ask:
                return .askOnAccess
            case .alwaysAllow:
                return .alwaysAllow
            case .alwaysDeny:
                return .alwaysDeny
            @unknown default:
                return .defaultPrompt
            }
        }
        return .unsupportedOS
    }
}
